#!/usr/bin/env python3
import sys
from pathlib import Path

def count(path, property):
    result = 0
    with open(path, encoding="utf-8", errors="ignore") as f:
        for line in f.readlines():
            if f"\"{property}\"" in line:
                result += int(line.split(f"\"{property}\":")[1].split(',')[0])
    return result

